"""Measure the models and write docs/results.md. Everything is seeded, so a rerun gives the same numbers."""

from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import confusion_matrix, precision_recall_fscore_support
from sklearn.model_selection import train_test_split

from intrusionsense.features import FEATURE_NAMES, MODEL_FEATURES
from intrusionsense.labels import ATTACK_LABELS
from intrusionsense.recorder import LABEL_COLUMN, NORMAL_LABEL
from intrusionsense.training import (
    CLASS_ID_BY_NAME,
    DAY_COLUMN,
    SEED,
    TRAIN_DAYS,
    UNKNOWN_DAY,
    fit_layer_1,
    fit_layer_2,
    layer_1_training_frame,
    load_cicids,
    load_recordings,
)

TEST_FRACTION = 0.2
ENGINE_THRESHOLD = 0.20  # the server's default L1_THRESHOLD
ATTACK_NAMES = [ATTACK_LABELS[i] for i in sorted(ATTACK_LABELS)]


def _features(frame: pd.DataFrame) -> np.ndarray:
    return frame[list(MODEL_FEATURES)].to_numpy()


def _flagged_suspicious(layer_1, frame: pd.DataFrame, threshold: float = ENGINE_THRESHOLD) -> np.ndarray:
    return layer_1.predict_proba(_features(frame))[:, 1] > threshold


def _table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join(["---"] * len(header)) + "|"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def layer_1_report(layer_1, test: pd.DataFrame) -> str:
    truth = (test[LABEL_COLUMN] != NORMAL_LABEL).to_numpy()
    flagged = _flagged_suspicious(layer_1, test)
    precision, recall, f1, _ = precision_recall_fscore_support(
        truth, flagged, average="binary", zero_division=0
    )
    normal = ~truth
    false_positive_rate = flagged[normal].mean() if normal.any() else float("nan")
    return _table(
        ["Test flows", "Precision", "Recall", "F1", "Normal flagged by mistake"],
        [[f"{len(test):,}", f"{precision:.4f}", f"{recall:.4f}", f"{f1:.4f}", f"{false_positive_rate:.4%}"]],
    )


def layer_2_report(layer_2, test: pd.DataFrame) -> str:
    attacks = test[test[LABEL_COLUMN] != NORMAL_LABEL]
    truth = attacks[LABEL_COLUMN].map(CLASS_ID_BY_NAME).to_numpy()
    predicted = layer_2.predict(_features(attacks))
    ids = sorted(ATTACK_LABELS)
    precision, recall, f1, support = precision_recall_fscore_support(
        truth, predicted, labels=ids, zero_division=0
    )
    per_class = _table(
        ["Attack type", "Precision", "Recall", "F1", "Test flows"],
        [
            [ATTACK_LABELS[i], f"{p:.4f}", f"{r:.4f}", f"{f:.4f}", f"{int(n):,}"]
            for i, p, r, f, n in zip(ids, precision, recall, f1, support, strict=True)
        ],
    )
    matrix = confusion_matrix(truth, predicted, labels=ids)
    confusion = _table(
        ["Actual \\ predicted", *ATTACK_NAMES],
        [[ATTACK_LABELS[i], *[f"{n:,}" for n in row]] for i, row in zip(ids, matrix, strict=True)],
    )
    return per_class + "\n\nConfusion matrix (rows are the real attack type):\n\n" + confusion


def held_out_day_report(cicids: pd.DataFrame) -> str:
    if set(cicids[DAY_COLUMN]) <= {UNKNOWN_DAY}:
        return (
            "Not measured: this dataset does not say which day each flow was captured, so there is no "
            "unseen day to test on. Point `--raw` at the raw CICIDS2017 day files (MachineLearningCVE) to get this test."
        )
    train = cicids[cicids[DAY_COLUMN].isin(TRAIN_DAYS)]
    test = cicids[~cicids[DAY_COLUMN].isin(TRAIN_DAYS)]
    layer_1 = fit_layer_1(layer_1_training_frame(train, pd.DataFrame(columns=[*FEATURE_NAMES, LABEL_COLUMN])))
    flagged = _flagged_suspicious(layer_1, test)
    rows = []
    for name in [NORMAL_LABEL, *ATTACK_NAMES]:
        mask = (test[LABEL_COLUMN] == name).to_numpy()
        if not mask.any():
            continue
        share = flagged[mask].mean()
        label = "Normal flows wrongly flagged" if name == NORMAL_LABEL else f"{name} flagged"
        rows.append([label, f"{int(mask.sum()):,}", f"{share:.2%}"])
    return _table(["Thursday and Friday traffic", "Flows", "Share"], rows)


def build_report(raw_dir: Path, recordings_dir: Path | None) -> str:
    dataset = load_cicids(raw_dir)
    recordings = load_recordings(recordings_dir)
    frame = dataset.frame
    strata = frame[LABEL_COLUMN]
    train, test = train_test_split(frame, test_size=TEST_FRACTION, random_state=SEED, stratify=strata)
    layer_1 = fit_layer_1(layer_1_training_frame(train, recordings))
    layer_2 = fit_layer_2(train)

    return f"""# Results

Generated by `intrusionsense evaluate`. Seeded: a rerun on the same data gives the same numbers.

## Data

- {dataset.rows_read:,} CICIDS2017 flows read, {dataset.rows_invalid:,} dropped as invalid (infinite or missing values),
  {dataset.rows_unmapped:,} dropped because their label has no class (Infiltration).
- **{dataset.duplicates_removed:,} exact duplicate flows collapsed before splitting**, leaving {len(frame):,} distinct flows,
  so no test flow also appears in training. In training each flow still counts as many times as it occurred, so
  common traffic keeps its weight; the tests below score distinct flows only, which is the harder, honest reading.
- {len(recordings):,} flows of recorded normal traffic were added to Layer 1 training.

## Layer 1: normal or suspicious (random split)

A stratified 80/20 split of the deduplicated data. A flow counts as suspicious above a probability of {ENGINE_THRESHOLD}.

{layer_1_report(layer_1, test)}

## Layer 2: which attack (random split)

Only attacks reach Layer 2, so only attacks are scored.

{layer_2_report(layer_2, test)}

## Layer 1 on traffic from days it never saw

Trained on {", ".join(d.title() for d in TRAIN_DAYS)} only, tested on Thursday and Friday. Bots, port scans, DDoS and
web attacks only occur on those two days, so this shows how well Layer 1 notices attack types it has never seen.
It is a harsher test than the random split, which mixes every day into training. (Needs the raw day files.)

{held_out_day_report(frame)}

Layer 2 has no held-out-day score: the attack types it must tell apart do not all occur in the training days.

## What these numbers do not show

- CICIDS2017 is a lab capture from 2017. Real networks differ, so expect lower scores on live traffic.
- The models read flow features computed by this project's sensor, which follows CICFlowMeter but is not identical to it.
- Rules (port scan, flood, web attack signatures) run before the models and are not scored here.
"""
